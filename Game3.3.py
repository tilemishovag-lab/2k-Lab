import random


player = {
    'name': '',
    'hp': 100,
    'keys': 0,
    'coins': 10
}


events = ['змея', 'ловушка', 'обвал', 'сундук']




def get_user_choice(max_option):
    """
    Функция для безопасного ввода выбора пользователя.
    Обрабатывает ошибки ввода через try-except (защита от нечислового ввода).
    """
    while True:
        try:
            choice = int(input('Выберите вариант: '))
            if 1 <= choice <= max_option:
                return choice
            else:
                print(f'Ошибка: введите число от 1 до {max_option}!')
        except ValueError:
            print('Ошибка: вы ввели не число! Попробуйте еще раз.')




def print_stats():
    """Функция для вывода текущих характеристик игрока."""
    print(f"--- [Игрок: HP={player['hp']} | Ключи={player['keys']} | Монеты={player['coins']}] ---")




def visit_shop():
    """Функция таинственного торговца (дополнительная мехника)."""
    print('\nВ углу комнаты вы замечаете странного торговца в капюшоне.')
    print('Торговец: "Приветствую, путник! Хочешь подлечиться?"')
    print('1 — Купить зелье здоровья (+20 HP) за 10 монет')
    print('2 — Пройти мимо')
    
    choice = get_user_choice(2)
    if choice == 1:
        if player['coins'] >= 10:
            player['coins'] -= 10
            player['hp'] += 20
            print('\nВы выпили зелье и восстановили 20 HP!')
            print_stats()
        else:
            print('\nУ вас недостаточно монет!')
    else:
        print('\nВы решили не рисковать и пошли дальше.')




def play_prologue():
    """Функция пролога (начало игры и первая развилка)."""
    print('Вы выходите из здания и садитесь в машину')
    print('Вы заводите мотор и выезжаете с парковки на главную дорогу')
    print('\nЧерез несколько минут вы подъезжаете к перекрестку')
    print('На светофоре горит красный свет. Загорелся зеленый свет')
    print('Вы начинаете движение')
    print('\nВдруг под колеса машины выбегает человек!')
    print('Вы резко тормозите, но столкновения избежать не удалось')
    
    print('\n1 — Уехать с места аварии')
    print('2 — Выйти и вызвать полицию')
    print('3 — Осмотреть пострадавшего на месте')
    
    return get_user_choice(3)




def play_room_1():
    """Функция обработки первой комнаты."""
    room = 1
    print(f'\n Вы вошли в комнату {room}')
    print('Перед вами две двери')
    print('1 — Левая дверь')
    print('2 — Правая дверь')
    
    door_choice = get_user_choice(2)
    
    if door_choice == 1:
        print('\nЛевая дверь заперта.')
        print('Вы осматриваете тумбочку рядом и находите ключ 🔑 и 15 монет 🪙!')
        player['keys'] += 1
        player['coins'] += 15
        print_stats()
        
        while True:
            print('\nТеперь перед вами двери:')
            print('1 — Левая дверь (заперта)')
            print('2 — Правая дверь (открыть найденным ключом)')
            
            next_choice = get_user_choice(2)
            
            if next_choice == 2:
                print('\nВы открываете правую дверь ключом.')
                print('Перед вами появляется длинный темный коридор.')
                break
            elif next_choice == 1:
                print('\nЛевая дверь всё ещё закрыта. Вам нужно идти в правую дверь!')


    elif door_choice == 2:
        print('\nВы открываете правую дверь.')
        print('За дверью находится ловушка!')
        print('Из темноты выползает змея и кусает вас 🐍')
        player['hp'] -= 20
        print('Вы потеряли 20 здоровья.')
        print_stats()




def play_room_2():
    """Функция обработки второй комнаты с интерактивными событиями."""
    room = 2
    print(f'\n Вы вошли в комнату {room}')
    print('Перед вами старая дверь с замком.')
    
    visit_shop()
    
    if player['keys'] > 0:
        print('\nВы используете найденный ключ 🔑')
        print('Дверь открывается...')
        
        event = random.choice(events)
        print(f'\nВ комнате происходит событие: {event.upper()}')
        
        if event == 'змея':
            print('Из темного угла выползает змея 🐍')
            player['hp'] -= 20
            print('Змея кусает вас!')
            print_stats()
            
        elif event == 'ловушка':
            print('Под ногами срабатывает скрытая нажимная плита!')
            player['hp'] -= 30
            print('Вы получаете повреждение!')
            print_stats()
            
        elif event == 'обвал':
            print('С потолка начинают падать камни!')
            player['hp'] -= 10
            print('Вы успеваете уклониться, но вас задевает обломком!')
            print_stats()


        elif event == 'сундук':
            print('В центре комнаты стоит старинный сундук 🧰!')
            print('Вы открываете его и находите 30 монет!')
            player['coins'] += 30
            print_stats()
    else:
        print('\nУ вас нет ключа, дверь остаётся закрытой.')
        print('Вам приходится выбивать дверь плечом! Вы теряете 10 HP.')
        player['hp'] -= 10
        print_stats()




def play_room_3():
    """Функция обработки финала игры."""
    room = 3
    print(f'\n Вы вошли в комнату {room}')
    print('Комната кажется совершенно пустой...')
    print('Вдруг пол начинает трескаться!')
    print('Трещины быстро распространяются по всей площади.')
    print('Земля проваливается под вашими ногами, и вы падаете вниз...')
    
    print('\n' + '='*40)
    print('Вы резко открываете глаза и подрываетесь с кровати.')
    print('Вы лежите у себя дома, на улице поют птицы.')
    print('Вы смотрите вокруг и понимаете, что всё это было лишь кошмарным сном.')
    print(f'Итоговые показатели сны: HP={player["hp"]}, Монеты={player["coins"]}')
    print('='*40)
    print('КОНЕЦ ИГРЫ')




def main():
    """Главная функция запуска игровой логики."""
    player['name'] = input('Введите имя персонажа: ')
    print(f'Добро пожаловать в игру, {player["name"]}!\n')
    
    choice = play_prologue()
    
    if choice == 1:
        print('\nВы решаете резко уехать с места аварии.')
        print('Сворачивая на незнакомую дорогу, вы теряете ориентир и замечаете заброшенное здание.')
        print('Вы заходите внутрь, чтобы спрятаться.')
    elif choice == 2:
        print('\nВы выходите из машины и звоните в полицию.')
        print('Пока вы ждёте патруль, поднимается густой туман. Чтобы укрыться от сырости, вы заходите в заброшенный дом рядом.')
    elif choice == 3:
        print('\nВы подбегаете к человеку, но вместо него на земле лежит странный кукольный манекен!')
        print('Испугавшись, вы отбегаете в сторону и оказываетесь у дверей заброшенного здания.')


    play_room_1()
    play_room_2()
    play_room_3()




if __name__ == '__main__':
    main()
